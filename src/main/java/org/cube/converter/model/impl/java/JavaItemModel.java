package org.cube.converter.model.impl.java;

import com.alibaba.fastjson2.JSONArray;
import com.alibaba.fastjson2.JSONObject;
import lombok.Getter;

import lombok.Setter;
import org.cube.converter.model.element.Cube;
import org.cube.converter.model.element.Parent;
import org.cube.converter.model.GeneralModel;
import org.cube.converter.util.element.Direction;
import org.cube.converter.util.element.Position2V;
import org.cube.converter.util.element.Position3V;
import org.cube.converter.util.math.MathUtil;
import org.cube.converter.util.minecraft.Transformation;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

@Getter
@Setter
public final class JavaItemModel extends GeneralModel {
    private Transformation defaultTransformation;
    private final Map<Direction, String> textures = new HashMap<>();
    private float scale = 1;

    public JavaItemModel(final Map<Direction, String> textures, final Position2V textureSize) {
        super(textureSize);
        this.textures.putAll(textures);
        this.defaultTransformation = null;
    }

    public JavaItemModel(final String texture, final Position2V textureSize) {
        super(textureSize);
        for (Direction direction : Direction.values()) {
            this.textures.put(direction, texture);
        }
        this.defaultTransformation = null;
    }

    public JavaItemModel(final String texture, final Position2V textureSize, final Transformation transformation) {
        super(textureSize);
        for (Direction direction : Direction.values()) {
            this.textures.put(direction, texture);
        }
        this.defaultTransformation = transformation;
    }

    public JSONObject compile() {
        final JSONObject json = new JSONObject();
        json.put("credit", "Generated by CubeConverter");
        json.put("texture_size", this.textureSize.toJson());

        // Textures.
        final JSONObject textures = new JSONObject();
        for (Map.Entry<Direction, String> direction : this.textures.entrySet()) {
            textures.put(direction.getKey().name(), direction.getValue());
        }
        json.put("textures", textures);

        final JSONArray elements = new JSONArray();
        final JSONArray groups = new JSONArray();

        for (Parent group : this.getParents()) {
            final JSONObject parent = new JSONObject();
            parent.put("name", group.getName());
            parent.put("origin", group.getPivot().withJavaOffset().toJson());
            parent.put("color", 0);

            // Children.
            final JSONArray children = new JSONArray();
            group.getCubes().forEach((k, v) -> children.add(k));
            parent.put("children", children);

            for (Map.Entry<Integer, Cube> entry : group.getCubes().entrySet()) {
                final Cube cube = entry.getValue();

                final JSONObject element = new JSONObject();
                // TODO: name, well it is that important? I don't care enough.
                element.put("name", cube.hashCode());

                final Position3V from = cube.getPosition().asJavaPosition(cube.getSize());
                element.put("from", from.toJson());
                element.put("to", from.add(cube.getSize()).toJson());
                if (cube.isThereOneAngleOnly()) {
                    element.put("rotation", compileAxis(cube));
                } else {
                    element.put("rotation", compileRotation(cube));
                }
                element.put("faces", compileUV(this.textureSize.getX(), this.textureSize.getY(), cube));
                elements.add(element);
            }

            groups.add(parent);
        }

        json.put("elements", elements);
        json.put("groups", groups);

        return json;
    }

    private JSONObject compileRotation(final Cube cube) {
        final Position3V rotation = cube.getRotation();

        final JSONObject object = new JSONObject();
        object.put("x", rotation.getX());
        object.put("y", rotation.getY());
        object.put("z", rotation.getZ());
        object.put("origin", cube.getPivot().withJavaOffset().toJson());

        return object;
    }

    private JSONObject compileAxis(final Cube cube) {
        final Position3V rotation = cube.getRotation();

        final JSONObject object = new JSONObject();
        object.put("angle", rotation.getX() != 0 ? rotation.getX() : rotation.getY() != 0 ? rotation.getY() : rotation.getZ());
        object.put("axis", cube.getAxis());
        object.put("origin", cube.getPivot().withJavaOffset().toJson());

        return object;
    }

    private JSONObject compileUV(final float textureWidth, final float textureHeight, final Cube element) {
        JSONObject faces = new JSONObject();

        for (Map.Entry<Direction, Float[]> entry : element.getUvMap().toJavaPerfaceUV(textureWidth, textureHeight).getUvMap().entrySet()) {
            if (entry.getValue() == null) {
                continue;
            }

            final JSONObject faceDirection = new JSONObject();
            final JSONArray array = new JSONArray();
            array.add(MathUtil.clamp(entry.getValue()[0], 0f, 16f));
            array.add(MathUtil.clamp(entry.getValue()[1], 0f, 16f));
            array.add(MathUtil.clamp(entry.getValue()[2], 0f, 16f));
            array.add(MathUtil.clamp(entry.getValue()[3], 0f, 16f));

            faceDirection.put("uv", array);
            faceDirection.put("texture", "#" + entry.getKey().name());
            Float uvRotation = element.getUvMap().getUvRotation().get(entry.getKey());
            if (uvRotation != null) {
                faceDirection.put("rotation", uvRotation);
            }

            faces.put(entry.getKey().name().toLowerCase(), faceDirection);
        }

        if (faces.isEmpty()) {
            final JSONObject face = new JSONObject();
            final JSONArray array = new JSONArray();
            List.of(0, 0, 0, 0).forEach(array::add);

            face.put("uv", array);
            face.put("texture", "#0");
            faces.put("down", face);
        }

        return faces;
    }
}